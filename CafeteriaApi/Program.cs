using Npgsql;
using Microsoft.EntityFrameworkCore;
using CafeteriaApi.Data;

var builder = WebApplication.CreateBuilder(args);
builder.Services.AddCors(o => o.AddPolicy("cocina", p =>
    p.AllowAnyOrigin().AllowAnyHeader().AllowAnyMethod()));

// 1. Registra la conexión a PostgreSQL (Railway)
// La cadena de conexión NO va en el código ni en appsettings.json: en Railway se entrega con la
// variable ConnectionStrings__DefaultConnection = ${{Postgres.DATABASE_URL}} (en tu PC, con user-secrets).
var connectionString = builder.Configuration.GetConnectionString("DefaultConnection");

if (string.IsNullOrWhiteSpace(connectionString))
    throw new InvalidOperationException(
        "Falta la cadena de conexion 'DefaultConnection'. " +
        "Definela como variable de entorno ConnectionStrings__DefaultConnection en el servidor.");

connectionString = NormalizarConexion(connectionString);

// Protección: fuera de desarrollo se rechaza cualquier base de datos local (localhost, 127.0.0.1...)
if (!builder.Environment.IsDevelopment() && EsServidorLocal(connectionString))
    throw new InvalidOperationException(
        "La cadena de conexion apunta a un servidor local. " +
        "En el servidor publico debe apuntar a una base de datos remota.");

builder.Services.AddDbContext<AppDbContext>(options =>
    options.UseNpgsql(connectionString));

// 2. Puerto: los hosts públicos (Railway, Render, Heroku...) indican el puerto en la variable PORT.
// Si no existe, se usa la configuración por defecto de ASP.NET (ASPNETCORE_URLS).
var puerto = Environment.GetEnvironmentVariable("PORT");
if (!string.IsNullOrEmpty(puerto))
    builder.WebHost.UseUrls($"http://0.0.0.0:{puerto}");

builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();

try
{
    builder.Services.AddSwaggerGen();
}
catch
{
    // Manejo para versiones con OpenAPI integrado
}

var app = builder.Build();
app.UseCors("cocina");

// 3. Crea las tablas y el menú inicial si no existen (equivale a cafeteria_postgres.sql).
// Se puede ejecutar en cada arranque: no borra datos ni duplica el menú.
using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
    db.Database.ExecuteSqlRaw("""
        CREATE TABLE IF NOT EXISTS productos (
            id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            categoria   VARCHAR(50)   NOT NULL,
            nombre      VARCHAR(100)  NOT NULL,
            precio      NUMERIC(10,2) NOT NULL,
            disponible  BOOLEAN       NOT NULL DEFAULT TRUE
        );
        CREATE TABLE IF NOT EXISTS pedidos (
            id_pedido   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cliente     VARCHAR(50)   NOT NULL,
            producto    VARCHAR(100)  NOT NULL,
            cantidad    INT           NOT NULL,
            precio_unit NUMERIC(10,2) NOT NULL,
            subtotal    NUMERIC(10,2) NOT NULL,
            estado      VARCHAR(20)   NOT NULL DEFAULT 'Pendiente'
        );
        INSERT INTO productos (categoria, nombre, precio, disponible)
        SELECT v.categoria, v.nombre, v.precio, v.disponible
        FROM (VALUES
            ('Cafes',     'Cafe Americano',            15.00, TRUE),
            ('Cafes',     'Cappuccino',                22.00, TRUE),
            ('Cafes',     'Latte Macchiato',           24.00, TRUE),
            ('Platillos', 'Sandwich de Jamon y Queso', 30.00, TRUE),
            ('Platillos', 'Omelette Tradicional',      35.00, TRUE),
            ('Platillos', 'Club Sandwich',             45.00, TRUE),
            ('Postres',   'Pie de Queso',              20.00, TRUE),
            ('Postres',   'Pastel de Chocolate',       25.00, TRUE),
            ('Postres',   'Crepe de Nutella',          28.00, TRUE)
        ) AS v(categoria, nombre, precio, disponible)
        WHERE NOT EXISTS (SELECT 1 FROM productos);
        """);
}

// 4. Swagger solo en desarrollo, o si se activa en el servidor con la variable Swagger__Enabled=true
if (app.Environment.IsDevelopment() || app.Configuration.GetValue<bool>("Swagger:Enabled"))
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.UseRouting();

// Mapear los controladores de la API
app.MapControllers();

app.Run();

// Railway entrega la conexión como URL (postgresql://usuario:clave@host:puerto/base); Npgsql necesita clave=valor
static string NormalizarConexion(string cadena)
{
    if (!cadena.StartsWith("postgres://") && !cadena.StartsWith("postgresql://")) return cadena;

    var uri = new Uri(cadena);
    var usuario = uri.UserInfo.Split(':', 2);
    return new NpgsqlConnectionStringBuilder
    {
        Host = uri.Host,
        Port = uri.Port > 0 ? uri.Port : 5432,
        Username = Uri.UnescapeDataString(usuario[0]),
        Password = usuario.Length > 1 ? Uri.UnescapeDataString(usuario[1]) : "",
        Database = uri.AbsolutePath.TrimStart('/'),
        SslMode = SslMode.Prefer
    }.ConnectionString;
}

// Indica si el servidor de la cadena de conexión es una máquina local
static bool EsServidorLocal(string cadena)
{
    var host = (new NpgsqlConnectionStringBuilder(cadena).Host ?? "").Trim().ToLowerInvariant();
    return (host is "" or "." or "(local)" or "localhost" or "127.0.0.1" or "::1") || host.StartsWith("/");
}
